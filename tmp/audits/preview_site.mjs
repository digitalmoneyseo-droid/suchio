import { chromium } from '@playwright/test';
import { readFile } from 'node:fs/promises';
const audits=JSON.parse(await readFile('src/content/audits.json','utf8'));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto(`http://127.0.0.1:3120/audit/${audits[0].code}`);
await page.waitForTimeout(1200);
await page.screenshot({path:'tmp/audits/site-desktop-v2.png'});
await page.locator('#measurements-title').scrollIntoViewIfNeeded();
await page.screenshot({path:'tmp/audits/site-measurements-v2.png'});
await page.setViewportSize({width:390,height:844});
await page.goto(`http://127.0.0.1:3120/fr/audit/${audits[0].code}`);
await page.waitForTimeout(800);
await page.screenshot({path:'tmp/audits/site-mobile-v2.png'});
await page.locator('#priority-title').scrollIntoViewIfNeeded();
await page.screenshot({path:'tmp/audits/site-priorities-mobile-v2.png'});
await page.locator('#audit-contact').scrollIntoViewIfNeeded();
await page.screenshot({path:'tmp/audits/site-contact-mobile-v2.png'});
await page.setViewportSize({width:320,height:844});
await page.goto(`http://127.0.0.1:3120/fr/audit/${audits[5].code}`);
const issues=await page.evaluate(()=>[...document.querySelectorAll('main h1,main h2,main h3,main p,main a')].filter(e=>e.getBoundingClientRect().right>innerWidth+1||e.getBoundingClientRect().left<0).map(e=>e.textContent));
if(issues.length)throw Error(JSON.stringify(issues));
await page.screenshot({path:'tmp/audits/site-narrow-v2.png'});
await browser.close();
